-- Nomor nota aman untuk multi-komputer.
create sequence if not exists public.sjb_invoice_seq start 1;

create or replace function public.sjb_next_invoice()
returns text
language sql
security invoker
as $$
  select 'SJB2-' || to_char(now() at time zone 'Asia/Jakarta','YYYYMMDD') || '-' ||
         lpad(nextval('public.sjb_invoice_seq')::text, 4, '0');
$$;

grant execute on function public.sjb_next_invoice() to authenticated;
